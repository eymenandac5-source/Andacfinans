export function findAssetPriceTry(
  assetType: 'fund' | 'crypto' | 'stock',
  assetId: string
): { symbol: string; name: string; priceTry: number; dailyChangePct: number } | null {
  if (assetType === 'fund') {
    const f = DEMO_FUNDS.find((item) => item.id === assetId);
    if (!f) return null;
    return { symbol: f.code, name: f.name, priceTry: f.price, dailyChangePct: f.dailyChangePct };
  }
  if (assetType === 'crypto') {
    const c = DEMO_CRYPTO.find((item) => item.id === assetId);
    if (!c) return null;
    return { symbol: c.symbol, name: c.name, priceTry: c.priceTry, dailyChangePct: c.change24hPct };
  }
  const s = DEMO_STOCKS.find((item) => item.id === assetId);
  if (!s) return null;
  return { symbol: s.ticker, name: s.name, priceTry: s.priceTry, dailyChangePct: s.dailyChangePct };
}
