function buildSeries(base: number, points: number, drift: number, volatility: number, seed: number): PricePoint[] {
  const result: PricePoint[] = [];
  let current = base;
  const now = new Date('2026-11-15T00:00:00Z');
  for (let i = points - 1; i >= 0; i--) {
    const d = new Date(now.getTime() - i * 24 * 60 * 60 * 1000);
    const wave = Math.sin((points - i + seed) * 0.48) * volatility + Math.cos((points - i) * 0.23 + seed) * (volatility * 0.45);
    current = Math.max(base * 0.55, current * (1 + drift + wave));
    result.push({
      date: d.toISOString().slice(0, 10),
      value: Number(current.toFixed(base < 10 ? 4 : 2)),
    });
  }
  return result;
}

